// Flat array of all programs for fast lookup and search
export const ALL_STRUCTURED_STUDY_PROGRAMS: StudyProgramItem[] =
  STRUCTURED_STUDY_PROGRAMS_BY_FIELD.flatMap((g) => g.programs);

/**
 * Filter & search study programs based on keywords, degree level, and academic field.
 */
export function searchStudyPrograms(
  query: string,
  degreeFilter?: string,
  fieldFilter?: string
): StudyProgramItem[] {
  const q = query.trim().toLowerCase();
  return ALL_STRUCTURED_STUDY_PROGRAMS.filter((item) => {
    // If degree filter is selected and is one of D3, D4, S1, S2
    if (degreeFilter && degreeFilter !== 'Semua' && degreeFilter !== 'Lainnya' && degreeFilter !== 'S3') {
      if (!item.degreeLevels.includes(degreeFilter as 'D3' | 'D4' | 'S1' | 'S2')) {
        return false;
      }
    }
    // If field filter is selected
    if (fieldFilter && fieldFilter !== 'all' && item.fieldId !== fieldFilter) {
      return false;
    }
    // If no query, pass
    if (!q) return true;

    // Match query against program name, field names, default faculty, and keywords
    return (
      item.name.toLowerCase().includes(q) ||
      item.fieldName.toLowerCase().includes(q) ||
      item.fieldEnglish.toLowerCase().includes(q) ||
      item.defaultFaculty.toLowerCase().includes(q) ||
      item.keywords.some((k) => k.toLowerCase().includes(q))
    );
  });
}

